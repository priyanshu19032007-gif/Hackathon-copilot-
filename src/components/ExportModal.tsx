import React, { useState } from 'react';
import { 
  X, 
  Download, 
  Copy, 
  Check, 
  FileText, 
  FileCode, 
  Printer, 
  Share2 
} from 'lucide-react';
import { HackathonBlueprint } from '../types/blueprint';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  blueprint: HackathonBlueprint;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  blueprint
}) => {
  const [copiedType, setCopiedType] = useState<string | null>(null);

  if (!isOpen) return null;

  const buildMarkdown = () => {
    return `# HACKATHON BLUEPRINT: ${blueprint.profile.title.toUpperCase()}
> ${blueprint.profile.tagline}

**Target Track:** ${blueprint.profile.hackathonTrack}
**Target Audience:** ${blueprint.profile.targetAudience}
**Duration:** ${blueprint.timeline.hackathonDuration} Hours

---

## 1. Executive Summary & Pitch
- **Problem Statement:** ${blueprint.profile.problemStatement}
- **Solution Overview:** ${blueprint.profile.solutionOverview}
- **The "Wow Factor":** ${blueprint.profile.wowFactor}
- **30-Second Elevator Pitch:** "${blueprint.pitchKit.elevatorPitch}"

---

## 2. MoSCoW Feature Scoping Matrix
${blueprint.features.map(f => `### ${f.name} [${f.tier.toUpperCase()}]
- Description: ${f.description}
- Estimated Dev Load: ${f.estimatedHours} Hours
- Role Assigned: ${f.assignedRole}
- Demo Impact Score: ${f.demoImpactScore}/10
`).join('\n')}

---

## 3. Recommended Tech Stack
${blueprint.techStack.map(t => `- **${t.category}**: \`${t.tool}\`
  - *Why it wins:* ${t.justification}
  - *Hackathon Tip:* ${t.hackathonTip}
`).join('\n')}

### Quickstart CLI Commands:
\`\`\`bash
${blueprint.cliSetupCommands.join('\n')}
\`\`\`

---

## 4. System Architecture
**Summary:** ${blueprint.architecture.summary}

### Nodes:
${blueprint.architecture.nodes.map(n => `- **${n.label}** (${n.category}): ${n.description} [Tech: ${n.tech}]`).join('\n')}

### Data Flow Sequence:
${blueprint.architecture.dataFlowSteps.map(s => `${s.step}. **${s.title}**: ${s.description} (${s.fromNode} -> ${s.toNode})`).join('\n')}

### Murphy's Law Offline Strategy:
${blueprint.architecture.offlineFallbackStrategy}

---

## 5. Database Schema & ERD
**Database Type:** ${blueprint.database.databaseType}

\`\`\`sql
${blueprint.database.sqlDDL}
\`\`\`

---

## 6. REST API Specifications
${blueprint.apis.map(a => `### \`${a.method} ${a.path}\`
${a.summary}
- Description: ${a.description}
- Status: ${a.status}

Request Body:
\`\`\`json
${a.requestBodySample}
\`\`\`

Response:
\`\`\`json
${a.responseSample}
\`\`\`
`).join('\n')}

---

## 7. Hour-by-Hour Execution Plan (${blueprint.timeline.hackathonDuration} Hours)
**Golden Rule:** ${blueprint.timeline.goldenRule}

${blueprint.timeline.phases.map(p => `### ${p.phaseName}
*Objective:* ${p.objective}
${p.tasks.map(t => `- [ ] **${t.title}** (${t.role}): ${t.deliverable}`).join('\n')}
`).join('\n')}

---

## 8. 2-Minute Demo Day Script
${blueprint.pitchKit.twoMinuteDemoScript.map(b => `### [${b.timestamp}] ${b.segment}
- **Visual On Screen:** ${b.visualOnScreen}
- **Spoken Script:** "${b.speakerScript}"
`).join('\n')}

---
Generated by **HackPilot AI Copilot**
`;
  };

  const downloadFile = (content: string, filename: string, mime: string) => {
    const blob = new Blob([content], { type: mime });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  const copyToClipboard = (text: string, type: string) => {
    navigator.clipboard.writeText(text);
    setCopiedType(type);
    setTimeout(() => setCopiedType(null), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/75 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="bg-slate-950 border border-slate-800 rounded-2xl w-full max-w-xl p-6 shadow-2xl space-y-5 animate-in fade-in zoom-in-95 duration-150">
        <div className="flex items-center justify-between pb-3 border-b border-slate-800">
          <div>
            <h3 className="text-lg font-extrabold text-white">
              Export Hackathon Blueprint
            </h3>
            <p className="text-xs text-slate-400">
              Download or copy your complete project blueprint for your team and Devpost submission.
            </p>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded-lg text-slate-400 hover:text-white hover:bg-slate-900 transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
          {/* Markdown Download */}
          <button
            onClick={() => downloadFile(buildMarkdown(), `${blueprint.profile.title.toLowerCase().replace(/\s+/g, '_')}_blueprint.md`, 'text/markdown')}
            className="p-4 rounded-xl bg-slate-900 hover:bg-slate-850 border border-slate-800 hover:border-emerald-500/50 text-left transition flex flex-col justify-between group"
          >
            <div className="flex items-center justify-between mb-2">
              <FileText className="w-5 h-5 text-emerald-400" />
              <Download className="w-4 h-4 text-slate-500 group-hover:text-emerald-400 transition" />
            </div>
            <div>
              <span className="font-bold text-sm text-white block">Download Markdown</span>
              <span className="text-xs text-slate-400">Complete HACKATHON_PLAN.md with all specs</span>
            </div>
          </button>

          {/* JSON Download */}
          <button
            onClick={() => downloadFile(JSON.stringify(blueprint, null, 2), `${blueprint.profile.title.toLowerCase().replace(/\s+/g, '_')}_blueprint.json`, 'application/json')}
            className="p-4 rounded-xl bg-slate-900 hover:bg-slate-850 border border-slate-800 hover:border-cyan-500/50 text-left transition flex flex-col justify-between group"
          >
            <div className="flex items-center justify-between mb-2">
              <FileCode className="w-5 h-5 text-cyan-400" />
              <Download className="w-4 h-4 text-slate-500 group-hover:text-cyan-400 transition" />
            </div>
            <div>
              <span className="font-bold text-sm text-white block">Download Raw JSON</span>
              <span className="text-xs text-slate-400">Structured data for automated CI/scripts</span>
            </div>
          </button>

          {/* Copy Markdown */}
          <button
            onClick={() => copyToClipboard(buildMarkdown(), 'md')}
            className="p-4 rounded-xl bg-slate-900 hover:bg-slate-850 border border-slate-800 hover:border-purple-500/50 text-left transition flex flex-col justify-between group"
          >
            <div className="flex items-center justify-between mb-2">
              <Copy className="w-5 h-5 text-purple-400" />
              {copiedType === 'md' ? (
                <Check className="w-4 h-4 text-emerald-400" />
              ) : (
                <span className="text-[10px] text-slate-500 font-mono">CLIPBOARD</span>
              )}
            </div>
            <div>
              <span className="font-bold text-sm text-white block">
                {copiedType === 'md' ? 'Copied to Clipboard!' : 'Copy Markdown Text'}
              </span>
              <span className="text-xs text-slate-400">Paste directly into team Slack / Discord</span>
            </div>
          </button>

          {/* Print / Save PDF */}
          <button
            onClick={() => window.print()}
            className="p-4 rounded-xl bg-slate-900 hover:bg-slate-850 border border-slate-800 hover:border-amber-500/50 text-left transition flex flex-col justify-between group"
          >
            <div className="flex items-center justify-between mb-2">
              <Printer className="w-5 h-5 text-amber-400" />
              <span className="text-[10px] text-slate-500 font-mono">PRINT/PDF</span>
            </div>
            <div>
              <span className="font-bold text-sm text-white block">Print / Save as PDF</span>
              <span className="text-xs text-slate-400">Formatted printable team reference sheet</span>
            </div>
          </button>
        </div>

        <div className="pt-2 text-center">
          <button
            onClick={onClose}
            className="text-xs font-semibold text-slate-400 hover:text-white transition"
          >
            Close Window
          </button>
        </div>
      </div>
    </div>
  );
};
